<#
.SYNOPSIS
    Prepares machine-local PowerShell startup files without installing tools.
.DESCRIPTION
    Run after installing or upgrading Oh My Posh, changing its theme, or changing
    GOPATH. setup.ps1 runs this automatically. No environment secrets are cached.
#>
[CmdletBinding()]
param(
    [string]$ThemePath = (Join-Path ([Environment]::GetFolderPath('MyDocuments')) 'PowerShell\Themes\dracula.omp.json'),
    [string]$OutputDirectory = (Join-Path $HOME '.cache\dotfiles\powershell')
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

if (-not (Test-Path -LiteralPath $ThemePath -PathType Leaf)) {
    throw "Prompt theme not found: $ThemePath. Run shell\powershell\setup.ps1 first."
}

$promptScript = (oh-my-posh init pwsh --config $ThemePath --print) -join [Environment]::NewLine
if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($promptScript)) {
    throw 'Oh My Posh could not generate its PowerShell initialization script.'
}
$tokens = $null
$parseErrors = $null
$null = [Management.Automation.Language.Parser]::ParseInput($promptScript, [ref]$tokens, [ref]$parseErrors)
if ($parseErrors.Count) {
    throw "Oh My Posh generated invalid PowerShell: $($parseErrors[0].Message)"
}

$extraPaths = @()
if (Get-Command go -ErrorAction SilentlyContinue) {
    $goPath = go env GOPATH
    if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($goPath)) {
        throw 'go env GOPATH failed while preparing PowerShell startup.'
    }
    foreach ($entry in ($goPath -split [IO.Path]::PathSeparator)) {
        $bin = Join-Path $entry 'bin'
        if (Test-Path -LiteralPath $bin -PathType Container) {
            $extraPaths += $bin
        }
    }
}

if (-not (Get-Command eza -ErrorAction SilentlyContinue)) {
    $ezaPaths = @(
        "$env:LOCALAPPDATA\Microsoft\WinGet\Packages\eza-community.eza_Microsoft.Winget.Source_8wekyb3d8bbwe\eza.exe",
        "$env:LOCALAPPDATA\Microsoft\WinGet\Links\eza.exe",
        "$env:ProgramFiles\eza\eza.exe",
        "${env:ProgramFiles(x86)}\eza\eza.exe"
    )
    $ezaPath = $ezaPaths | Where-Object { Test-Path -LiteralPath $_ -PathType Leaf } | Select-Object -First 1
    if ($ezaPath) {
        $extraPaths += Split-Path -Parent $ezaPath
    } else {
        Write-Warning 'eza is not installed. Run shell\powershell\setup.ps1 to provision it.'
    }
}

$promptPath = Join-Path $OutputDirectory 'prompt.ps1'
$startupPath = Join-Path $OutputDirectory 'startup.ps1'
$startup = @(
    '# Generated by dotfiles shell\powershell\prepare-startup.ps1. Do not edit.',
    ("& '{0}'" -f $promptPath.Replace("'", "''")),
    # The generated prompt contains a setup-time ID. Each shell needs its own.
    '$env:POSH_SESSION_ID = [guid]::NewGuid().ToString()'
)
foreach ($entry in ($extraPaths | Select-Object -Unique)) {
    $quoted = $entry.Replace("'", "''")
    $startup += "if ((`$env:PATH -split ';') -notcontains '$quoted') { `$env:PATH += ';$quoted' }"
}

New-Item -ItemType Directory -Path $OutputDirectory -Force | Out-Null
Set-Content -LiteralPath $promptPath -Value $promptScript -Encoding UTF8
Set-Content -LiteralPath $startupPath -Value $startup -Encoding UTF8
Write-Host "Prepared PowerShell startup at $startupPath"
